static PyObject *pyvl_multipole_rich_compare(PyObject *self, PyObject *other, int op)
{
    const module_state_t *state = get_module_state(Py_TYPE(self));
    if (!state)
        return NULL;

    if (op != Py_EQ && op != Py_NE)
    {
        Py_RETURN_NOTIMPLEMENTED;
    }
    if (!PyObject_TypeCheck(other, state->multipole_type))
    {
        Py_RETURN_NOTIMPLEMENTED;
    }

    const PyVL_MultipoleObject *a = (const PyVL_MultipoleObject *)self;
    const PyVL_MultipoleObject *b = (const PyVL_MultipoleObject *)other;

    bool eq = true;
    if (a->multipole.order != b->multipole.order)
        eq = false;

    if (eq)
    {
        const real3_t dc = real3_sub(a->multipole.center, b->multipole.center);
        if (real3_dot(dc, dc) > 1e-20)
            eq = false;
    }

    if (eq)
    {
        const size_t n = multipole_num_coeffs(a->multipole.order);
        if (memcmp(a->coeff_buffer, b->coeff_buffer, sizeof(double) * 3 * n) != 0)
            eq = false;
    }

    const bool result = (op == Py_EQ) ? eq : !eq;
    if (result)
        Py_RETURN_TRUE;
    Py_RETURN_FALSE;
}

