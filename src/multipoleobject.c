PyDoc_STRVAR(pyvl_multipole_shift_doc,
             "shift(center: VecLike3, work_order: int | None = None, /) -> Multipole\n"
             "Create a new Multipole at *center* with coefficients shifted from this one.\n"
             "\n"
             "The new expansion has the same order as this one.\n"
             "\n"
             "Parameters\n"
             "----------\n"
             "center : VecLike3\n"
             "    Center of the new multipole expansion.\n"
             "work_order : int, optional\n"
             "    Internal expansion order for the binomial series (defaults to ``self.order``).\n"
             "\n"
             "Returns\n"
             "-------\n"
             "Multipole\n"
             "    New multipole expansion at the requested center.\n"
             "\n"
             "See Also\n"
             "--------\n"
             "shift_to : Shift to match another Multipole's center.\n"
             "\n"
             "Examples\n"
             "--------\n"
             ">>> from pyvl.cvl import Multipole\n"
             ">>> m = Multipole(2, (0., 0., 0.))\n"
             ">>> m2 = m.shift((1., 0., 0.))\n"
             ">>> m2.center\n"
             "array([1., 0., 0.])\n");

static PyObject *pyvl_multipole_shift(PyObject *self, PyTypeObject *defining_class, PyObject *const *args,
                                      const Py_ssize_t nargs, const PyObject *kwnames)
{
    const PyVL_MultipoleObject *this;
    const module_state_t *state;
    if (!ensure_multipole_and_state(defining_class, self, &this, &state))
        return NULL;

    PyObject *center_obj;
    Py_ssize_t work_order = -1; // -1 means unset
    if (parse_arguments_check(
            (cpyutl_argument_t[]){
                {.type = CPYARG_TYPE_PYTHON, .p_val = (void *)&center_obj, .kwname = "center"},
                {.type = CPYARG_TYPE_SSIZE, .p_val = &work_order, .kwname = "work_order", .optional = true},
                {0},
            },
            args, nargs, kwnames) < 0)
        return NULL;

    real3_t new_center;
    if (!pyvl_veclike3_to_real3(center_obj, &new_center))
        return NULL;

    const unsigned in_order = this->multipole.order;
    const unsigned out_order = in_order;
    const unsigned wo = (work_order < 0) ? out_order : (unsigned)work_order;

    if (wo < in_order || wo < out_order)
    {
        PyErr_SetString(PyExc_ValueError, "work_order must be >= both input and output orders.");
        return NULL;
    }

    // Allocate the new Multipole
    PyVL_MultipoleObject *out = (PyVL_MultipoleObject *)state->multipole_type->tp_alloc(state->multipole_type, 0);
    if (!out)
        return NULL;

    out->multipole.order = out_order;
    out->multipole.center = new_center;
    out->coeff_buffer = pyvl_allocate_coeffs(out_order, &out->multipole);
    if (!out->coeff_buffer)
    {
        Py_DECREF(out);
        return NULL;
    }

    // Work buffers
    const size_t shift_dim = (size_t)wo + 1;
    const size_t shift_plane = shift_dim * shift_dim;
    const size_t n_coeffs = multipole_num_coeffs(wo);

    double *shift_exp = (double *)PyMem_Malloc(sizeof(double) * 3 * shift_plane);
    double *pse = (double *)PyMem_Malloc(sizeof(double) * 2 * n_coeffs);
    if (!shift_exp || !pse)
    {
        PyMem_Free(pse);
        PyMem_Free(shift_exp);
        Py_DECREF(out);
        PyErr_NoMemory();
        return NULL;
    }

    multipole_add_shift(&this->multipole, &out->multipole, wo, shift_exp, pse);

    PyMem_Free(pse);
    PyMem_Free(shift_exp);
    return (PyObject *)out;
}

