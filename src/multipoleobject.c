PyDoc_STRVAR(pyvl_multipole_add_sources_doc,
             "add_sources(points: ArrayLike, values: ArrayLike, /) -> None\n"
             "Add source contributions to this multipole expansion.\n"
             "\n"
             "Parameters\n"
             "----------\n"
             "points : (..., 3) array_like\n"
             "    Positions of the sources.\n"
             "values : (..., 3) array_like\n"
             "    Vector values of the sources (must have the same batch shape as points).\n"
             "\n"
             "Examples\n"
             "--------\n"
             ">>> import numpy as np\n"
             ">>> from pyvl.cvl import Multipole\n"
             ">>> m = Multipole(2, (0., 0., 0.))\n"
             ">>> m.add_sources(np.array([[1., 0., 0.]]), np.array([[0., 1., 0.]]))\n");

static PyObject *pyvl_multipole_add_sources(PyObject *self, PyTypeObject *defining_class, PyObject *const *args,
                                            const Py_ssize_t nargs, const PyObject *kwnames)
{
    PyVL_MultipoleObject *this;
    const module_state_t *state;
    if (!ensure_multipole_and_state(defining_class, self, (const PyVL_MultipoleObject **)&this, &state))
        return NULL;

    PyObject *points_obj, *values_obj;
    if (parse_arguments_check(
            (cpyutl_argument_t[]){
                {.type = CPYARG_TYPE_PYTHON, .p_val = (void *)&points_obj},
                {.type = CPYARG_TYPE_PYTHON, .p_val = (void *)&values_obj},
                {0},
            },
            args, nargs, kwnames) < 0)
        return NULL;

    size_t n_points, n_values;
    PyArrayObject *points_arr = pyvl_flatten_points(points_obj, &n_points);
    if (!points_arr)
        return NULL;
    PyArrayObject *values_arr = pyvl_flatten_points(values_obj, &n_values);
    if (!values_arr)
    {
        Py_DECREF(points_arr);
        return NULL;
    }

    if (n_points != n_values)
    {
        PyErr_Format(PyExc_ValueError, "Number of points (%zu) does not match number of values (%zu).", n_points,
                     n_values);
        Py_DECREF(points_arr);
        Py_DECREF(values_arr);
        return NULL;
    }

    const real3_t *points_data = (const real3_t *)PyArray_DATA(points_arr);
    const real3_t *values_data = (const real3_t *)PyArray_DATA(values_arr);

    const unsigned order = this->multipole.order;
    const size_t scratch = multipole_scratch_size(order);

    // Allocate scratch buffers on heap (safe for any order)
    double *cur = (double *)PyMem_Malloc(scratch * sizeof(double));
    double *nxt = (double *)PyMem_Malloc(scratch * sizeof(double));
    if (!cur || !nxt)
    {
        PyMem_Free(nxt);
        PyMem_Free(cur);
        Py_DECREF(points_arr);
        Py_DECREF(values_arr);
        PyErr_NoMemory();
        return NULL;
    }

    for (size_t i = 0; i < n_points; ++i)
    {
        memset(cur, 0, scratch * sizeof(double));
        memset(nxt, 0, scratch * sizeof(double));
        multipole_update(&this->multipole, this->multipole.center, points_data[i], values_data[i], cur, nxt);
    }

    PyMem_Free(nxt);
    PyMem_Free(cur);
    Py_DECREF(points_arr);
    Py_DECREF(values_arr);
    Py_RETURN_NONE;
}

