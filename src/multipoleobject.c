/**
 * @brief Type-check self and retrieve module state (bound-method helper).
 */
static bool ensure_multipole_and_state(PyTypeObject *defining_class, PyObject *self,
                                       const PyVL_MultipoleObject **p_this, const module_state_t **p_state)
{
    const module_state_t *state = NULL;
    if (defining_class)
        state = PyType_GetModuleState(defining_class);
    else
        state = get_module_state(Py_TYPE(self));

    if (!state)
        return false;

    if (!PyObject_TypeCheck(self, state->multipole_type))
    {
        PyErr_Format(PyExc_TypeError, "Self was not \"%s\" but was \"%s\".", state->multipole_type->tp_name,
                     Py_TYPE(self)->tp_name);
        return false;
    }
    *p_this = (const PyVL_MultipoleObject *)self;
    *p_state = state;
    return true;
}

/**
 * @brief Parse a VecLike3 argument into a real3_t.
 *
 * Accepts any (3,) contiguous double array-like.
 */
static bool pyvl_veclike3_to_real3(PyObject *obj, real3_t *out)
{
    PyArrayObject *arr =
        (PyArrayObject *)PyArray_FROMANY(obj, NPY_DOUBLE, 1, 1, NPY_ARRAY_C_CONTIGUOUS | NPY_ARRAY_ALIGNED);
    if (!arr)
        return false;
    if (PyArray_DIM(arr, 0) != 3)
    {
        PyErr_Format(PyExc_ValueError, "Expected a 3-element vector, got %" NPY_INTP_FMT " elements.",
                     PyArray_DIM(arr, 0));
        Py_DECREF(arr);
        return false;
    }
    const double *data = PyArray_DATA(arr);
    out->x = data[0];
    out->y = data[1];
    out->z = data[2];
    Py_DECREF(arr);
    return true;
}

/**
 * @brief Convert a (..., 3) array-like to a contiguous (N, 3) double array and return N.
 *
 * The caller owns the returned PyArrayObject reference.
 */
static PyArrayObject *pyvl_flatten_points(PyObject *obj, size_t *p_n)
{
    PyArrayObject *arr =
        (PyArrayObject *)PyArray_FROMANY(obj, NPY_DOUBLE, 2, INT_MAX, NPY_ARRAY_C_CONTIGUOUS | NPY_ARRAY_ALIGNED);
    if (!arr)
        return NULL;

    const int ndim = PyArray_NDIM(arr);
    if (PyArray_DIM(arr, ndim - 1) != 3)
    {
        PyErr_Format(PyExc_ValueError, "Last axis must have size 3, got %" NPY_INTP_FMT ".",
                     PyArray_DIM(arr, ndim - 1));
        Py_DECREF(arr);
        return NULL;
    }

    size_t n = 1;
    for (int i = 0; i < ndim - 1; ++i)
        n *= PyArray_DIM(arr, i);
    *p_n = n;
    return arr;
}

/**
 * @brief Allocate the 3-component coefficient buffer and set coeff pointers.
 *
 * Caller owns the returned buffer (must be freed with PyMem_Free).
 */
static double *pyvl_allocate_coeffs(unsigned order, multipole_t *mp)
{
    const size_t n_coeffs = multipole_num_coeffs(order);
    const size_t nbytes = sizeof(double) * 3 * n_coeffs;
    double *buf = (double *)PyMem_Malloc(nbytes);
    if (!buf)
    {
        PyErr_NoMemory();
        return NULL;
    }
    memset(buf, 0, nbytes);
    mp->coeffs_x = buf;
    mp->coeffs_y = buf + n_coeffs;
    mp->coeffs_z = buf + 2 * n_coeffs;
    return buf;
}

