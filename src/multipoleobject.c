static PyObject *pyvl_multipole_get_order(PyObject *self, void *Py_UNUSED(closure))
{
    const PyVL_MultipoleObject *this = (const PyVL_MultipoleObject *)self;
    return PyLong_FromUnsignedLong(this->multipole.order);
}

static PyObject *pyvl_multipole_get_center(PyObject *self, void *Py_UNUSED(closure))
{
    const PyVL_MultipoleObject *this = (const PyVL_MultipoleObject *)self;
    PyArrayObject *out = (PyArrayObject *)PyArray_SimpleNew(1, (const npy_intp[1]){3}, NPY_DOUBLE);
    if (!out)
        return NULL;
    double *data = PyArray_DATA(out);
    data[0] = this->multipole.center.x;
    data[1] = this->multipole.center.y;
    data[2] = this->multipole.center.z;
    return (PyObject *)out;
}

static int pyvl_multipole_set_center(PyObject *self, PyObject *value, void *Py_UNUSED(closure))
{
    PyVL_MultipoleObject *this = (PyVL_MultipoleObject *)self;
    if (!value)
    {
        PyErr_SetString(PyExc_TypeError, "Cannot delete the center property.");
        return -1;
    }
    if (!pyvl_veclike3_to_real3(value, &this->multipole.center))
        return -1;
    return 0;
}

