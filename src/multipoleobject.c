PyDoc_STRVAR(pyvl_multipole_eval_doc,
             "eval(points: ArrayLike, out: npt.NDArray[np.double] | None = None, /) -> npt.NDArray[np.double]\n"
             "Evaluate the multipole expansion at one or more points.\n"
             "\n"
             "Parameters\n"
             "----------\n"
             "points : (..., 3) array_like\n"
             "    Points at which to evaluate. All leading dimensions are preserved in the output.\n"
             "out : (..., 3) ndarray, optional\n"
             "    Output array. Must have the same shape as ``points``, be writable,\n"
             "    C-contiguous, and aligned.\n"
             "\n"
             "Returns\n"
             "-------\n"
             "(..., 3) ndarray\n"
             "    Induced vector at each point.\n"
             "\n"
             "Examples\n"
             "--------\n"
             ">>> import numpy as np\n"
             ">>> from pyvl.cvl import Multipole\n"
             ">>> m = Multipole(0, (0., 0., 0.))\n"
             ">>> m.eval(np.array([[1., 0., 0.]]))\n"
             "array([[0., 0., 0.]])\n");

static PyObject *pyvl_multipole_eval(PyObject *self, PyTypeObject *defining_class, PyObject *const *args,
                                     const Py_ssize_t nargs, const PyObject *kwnames)
{
    const PyVL_MultipoleObject *this;
    const module_state_t *state;
    if (!ensure_multipole_and_state(defining_class, self, &this, &state))
        return NULL;

    PyObject *points_obj;
    PyArrayObject *out = NULL;
    if (parse_arguments_check(
            (cpyutl_argument_t[]){
                {.type = CPYARG_TYPE_PYTHON, .p_val = (void *)&points_obj, .kwname = "points"},
                {.type = CPYARG_TYPE_PYTHON,
                 .p_val = (void *)&out,
                 .kwname = "out",
                 .optional = true,
                 .type_check = &PyArray_Type},
                {0},
            },
            args, nargs, kwnames) < 0)
        return NULL;

    size_t n_points;
    PyArrayObject *points_arr = pyvl_flatten_points(points_obj, &n_points);
    if (!points_arr)
        return NULL;

    const int ndim = PyArray_NDIM(points_arr);
    const npy_intp *dims = PyArray_DIMS(points_arr);

    if (out)
    {
        if (check_input_array(out, ndim, dims, NPY_DOUBLE,
                              NPY_ARRAY_C_CONTIGUOUS | NPY_ARRAY_WRITEABLE | NPY_ARRAY_ALIGNED, "out") < 0)
        {
            Py_DECREF(points_arr);
            return NULL;
        }
        Py_INCREF(out);
    }
    else
    {
        out = (PyArrayObject *)PyArray_SimpleNew(ndim, dims, NPY_DOUBLE);
        if (!out)
        {
            Py_DECREF(points_arr);
            return NULL;
        }
    }

    const real3_t *points_data = (const real3_t *)PyArray_DATA(points_arr);
    real3_t *out_data = (real3_t *)PyArray_DATA(out);

    const multipole_t *mp = &this->multipole;

    Py_BEGIN_ALLOW_THREADS;
    for (size_t i = 0; i < n_points; ++i)
    {
        out_data[i] = multipole_eval(mp, points_data[i]);
    }
    Py_END_ALLOW_THREADS;

    Py_DECREF(points_arr);
    return (PyObject *)out;
}

