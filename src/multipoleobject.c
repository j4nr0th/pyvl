PyDoc_STRVAR(pyvl_multipole_from_sources_doc,
             "from_sources(order: int, center: VecLike3, points: ArrayLike, values: ArrayLike, /) -> Multipole\n"
             "Create a multipole expansion from a set of source points.\n"
             "\n"
             "Parameters\n"
             "----------\n"
             "order : int\n"
             "    Order of the multipole expansion.\n"
             "center : VecLike3\n"
             "    Center of the expansion.\n"
             "points : (..., 3) array_like\n"
             "    Positions of the source particles.\n"
             "values : (..., 3) array_like\n"
             "    Vector values of the source particles.\n"
             "\n"
             "Returns\n"
             "-------\n"
             "Multipole\n"
             "    New multipole expansion with sources built in.\n"
             "\n"
             "Examples\n"
             "--------\n"
             ">>> import numpy as np\n"
             ">>> from pyvl.cvl import Multipole\n"
             ">>> pts = np.array([[1., 0., 0.], [0., 1., 0.], [0., 0., 1.]])\n"
             ">>> vals = np.array([[1., 0., 0.], [0., 1., 0.], [0., 0., 1.]])\n"
             ">>> m = Multipole.from_sources(2, (0., 0., 0.), pts, vals)\n"
             ">>> m.order\n"
             "2\n");

static PyObject *pyvl_multipole_from_sources(PyTypeObject *type, PyObject *const *args, const Py_ssize_t nargs,
                                             const PyObject *kwnames)
{
    const module_state_t *state = get_module_state(type);
    if (!state)
        return NULL;

    Py_ssize_t order;
    PyObject *center_obj, *points_obj, *values_obj;
    if (parse_arguments_check(
            (cpyutl_argument_t[]){
                {.type = CPYARG_TYPE_SSIZE, .p_val = &order},
                {.type = CPYARG_TYPE_PYTHON, .p_val = (void *)&center_obj},
                {.type = CPYARG_TYPE_PYTHON, .p_val = (void *)&points_obj},
                {.type = CPYARG_TYPE_PYTHON, .p_val = (void *)&values_obj},
                {0},
            },
            args, nargs, kwnames) < 0)
        return NULL;

    real3_t center;
    if (!pyvl_veclike3_to_real3(center_obj, &center))
        return NULL;

    size_t n_pts, n_vals;
    PyArrayObject *points_arr = pyvl_flatten_points(points_obj, &n_pts);
    if (!points_arr)
        return NULL;
    PyArrayObject *values_arr = pyvl_flatten_points(values_obj, &n_vals);
    if (!values_arr)
    {
        Py_DECREF(points_arr);
        return NULL;
    }

    if (n_pts != n_vals)
    {
        PyErr_Format(PyExc_ValueError, "Number of points (%zu) does not match number of values (%zu).", n_pts, n_vals);
        Py_DECREF(points_arr);
        Py_DECREF(values_arr);
        return NULL;
    }

    if (order < 0)
    {
        PyErr_SetString(PyExc_ValueError, "Order must be non-negative.");
        return NULL;
    }
    const unsigned uorder = (unsigned)order;

    const size_t n_coeffs = multipole_num_coeffs(uorder);
    const size_t scratch = multipole_scratch_size(uorder);
    // multipole_create checks: num_coeffs >= max(3 * n_coeffs, scratch)
    const size_t coeff_buf_size = 3 * n_coeffs;
    const size_t num_coeffs_for_create = (coeff_buf_size > scratch) ? coeff_buf_size : scratch;

    // We allocate a single block: 3*n_coeffs for coeffs + 2*scratch for cur/nxt
    double *coeffs = (double *)PyMem_Malloc(sizeof(double) * (coeff_buf_size + 2 * scratch));
    double *cur = coeffs + coeff_buf_size;
    double *nxt = cur + scratch;
    if (!coeffs)
    {
        Py_DECREF(points_arr);
        Py_DECREF(values_arr);
        PyErr_NoMemory();
        return NULL;
    }

    const real3_t *points_data = (const real3_t *)PyArray_DATA(points_arr);
    const real3_t *values_data = (const real3_t *)PyArray_DATA(values_arr);

    multipole_t mp;

    // Zero scratch areas before calling create
    memset(cur, 0, scratch * sizeof(double));
    memset(nxt, 0, scratch * sizeof(double));

    const bool ok = multipole_create(uorder, (unsigned)num_coeffs_for_create, coeffs, center, (unsigned)n_pts,
                                     points_data, values_data, cur, nxt, &mp);
    Py_DECREF(points_arr);
    Py_DECREF(values_arr);

    if (!ok)
    {
        PyMem_Free(coeffs);
        PyErr_SetString(PyExc_RuntimeError, "multipole_create failed.");
        return NULL;
    }

    // Build the Python object, transfer ownership of coeffs
    PyVL_MultipoleObject *self = (PyVL_MultipoleObject *)type->tp_alloc(type, 0);
    if (!self)
    {
        PyMem_Free(coeffs);
        return NULL;
    }

    self->multipole = mp;
    self->multipole.order = uorder;
    self->coeff_buffer = coeffs; // coeffs_x/y/z already point inside this buffer

    return (PyObject *)self;
}

