static PyObject *pyvl_multipole_new(PyTypeObject *type, PyObject *args, PyObject *kwargs)
{
    PyVL_MultipoleObject *self = (PyVL_MultipoleObject *)type->tp_alloc(type, 0);
    if (!self)
        return NULL;

    self->coeff_buffer = NULL;
    self->multipole.order = 0;
    self->multipole.center = (real3_t){{0}};
    self->multipole.coeffs_x = NULL;
    self->multipole.coeffs_y = NULL;
    self->multipole.coeffs_z = NULL;

    unsigned order;
    PyObject *center_obj;
    if (!PyArg_ParseTupleAndKeywords(args, kwargs, "IO", (char *[3]){"order", "center", NULL}, &order, &center_obj))
    {
        Py_DECREF(self);
        return NULL;
    }

    if (!pyvl_veclike3_to_real3(center_obj, &self->multipole.center))
    {
        Py_DECREF(self);
        return NULL;
    }

    self->multipole.order = order;
    self->coeff_buffer = pyvl_allocate_coeffs(order, &self->multipole);
    if (!self->coeff_buffer)
    {
        Py_DECREF(self);
        return NULL;
    }

    return (PyObject *)self;
}

static void pyvl_multipole_dealloc(PyObject *self)
{
    PyObject_GC_UnTrack(self);
    PyVL_MultipoleObject *this = (PyVL_MultipoleObject *)self;
    PyMem_Free(this->coeff_buffer);
    this->coeff_buffer = NULL;
    PyTypeObject *type = Py_TYPE(self);
    type->tp_free(self);
    Py_DECREF(type);
}

